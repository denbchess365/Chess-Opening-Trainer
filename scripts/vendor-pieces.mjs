// Dev-only: downloads extra piece sets from lichess-org/lila once and embeds them
// as data URIs in src/styles/pieces.css (committed, so the app needs no network).
//   merida   — Armando Hernandez Marroquin, GPLv2+
//   chessnut — Alexis Luengas, Apache-2.0
import { writeFileSync } from 'node:fs';

const sets = ['merida', 'chessnut'];
const roles = { P: 'pawn', N: 'knight', B: 'bishop', R: 'rook', Q: 'queen', K: 'king' };
let css = '/* Generated by scripts/vendor-pieces.mjs — piece sets from lichess-org/lila (see LICENSES/). */\n';
for (const set of sets) {
  for (const color of ['w', 'b']) {
    for (const [r, role] of Object.entries(roles)) {
      const url = `https://raw.githubusercontent.com/lichess-org/lila/master/public/piece/${set}/${color}${r}.svg`;
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${url}: ${res.status}`);
      const b64 = Buffer.from(await res.text()).toString('base64');
      css += `.pieces-${set} .cg-wrap piece.${role}.${color === 'w' ? 'white' : 'black'} { background-image: url('data:image/svg+xml;base64,${b64}'); }\n`;
    }
  }
}
writeFileSync('src/styles/pieces.css', css);
console.log('wrote src/styles/pieces.css', css.length);
